import { keyedAlphabet, substitute } from "../utils/ciphers";

// Original teaching passage, deliberately rich in linked THE / THA / HER groups.
export const SUBSTITUTION_PLAIN =
  "THE THREE FRIENDS READ THE LETTER TOGETHER. THE LETTER SAID THAT THE PATH LED TO THE RIVER. " +
  "HER MAP SHOWED THAT THE BRIDGE WAS NEAR THE TOWER. THEY AGREED THAT THE RED MARK ON HER MAP WAS THE NEXT CLUE. " +
  "AT THE BRIDGE THEY FOUND ANOTHER LETTER. IT SAID THAT THE TREASURE WAS UNDER THE THIRD STONE. " +
  "HER FRIEND CHECKED THE STONES WHILE THE OTHERS READ THE LETTER AGAIN. THERE WAS A SMALL BOX THERE. " +
  "THE NOTE IN THE BOX SAID THAT THEIR REAL TREASURE WAS THE TIME THEY HAD SPENT TOGETHER. " +
  "THE FRIENDS TOOK HER MAP BACK TO THE CLUB SO THAT THE OTHER MEMBERS COULD TRY THE SAME WALK.";
export const SUBSTITUTION_ALPHABET = keyedAlphabet("ORANGE");
export const SUBSTITUTION_CIPHER = substitute(
  SUBSTITUTION_PLAIN,
  SUBSTITUTION_ALPHABET,
  false,
  true,
);
export const encodedGroup = (plain: string) => substitute(plain, SUBSTITUTION_ALPHABET, false);
